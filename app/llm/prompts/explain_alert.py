
def build_explain_alert_prompt(fallback_text: str) -> str:
    return (
        "Ты — помощник крипто-трейдера. Дай простой и понятный технический анализ на основе текста ниже.\n"
        "Используй ТОЛЬКО цены и уровни, которые уже есть в сообщении. Ничего не выдумывай.\n"
        "Ценовой уровень алерта — это пользовательская настройка и НЕ является уровнем поддержки или сопротивления.\n\n"

        "Требования к стилю:\n"
        "- Текст должен быть связным и объясняющим, без телеграфных фраз.\n"
        "- 3 абзаца, каждый абзац с новой строки.\n"
        "- Используй не больше 3–4 эмодзи на всё сообщение.\n"
        "- Избегай повторения одних и тех же слов в пределах одного абзаца.\n"
        "- Используй ТОЛЬКО HTML-разметку.\n"
        "- Для выделения жирным используй только HTML-теги <b>...</b>.\n"
        "- Никогда не используй Markdown-разметку (**).\n"
        "- ВАЖНО: это Telegram HTML. Разрешены только теги <b>, <i>, <u>, <s>, <code>, <pre>, <a>.\n"
        "- Запрещены любые другие HTML-теги, особенно: <p>, <br/>, <div>, <span>, <h1> и т.д.\n"
        "- Выделяй жирным:\n"
        " • заголовки абзацев,\n"
        " • ключевые термины (название монеты, поддержка, сопротивление, тренд),\n"
        " • все цены и уровни.\n"
        "- Не выделяй жирным целые предложения.\n"
        "- Можно использовать слова: 'реакция', 'тест', 'удержание', 'пробой', 'импульс', 'тренд'.\n"
        "- Нельзя использовать: 'покупатели', 'продавцы', 'давление', 'с высокой вероятностью', "
        "'совет', 'вход', 'стоп'.\n\n"

        "Логика уровней (обязательно соблюдай):\n"
        "- Если обсуждается <b>сопротивление</b>:\n"
        "  • <b>Удержание</b> сопротивления = возможна реакция/замедление/откат.\n"
        "  • <b>Пробой</b> сопротивления = следующий ориентир — следующие уровни сопротивления (ростовый сценарий).\n"
        "- Если обсуждается <b>поддержка</b>:\n"
        "  • <b>Удержание</b> поддержки = возможна реакция/отскок/стабилизация.\n"
        "  • <b>Пробой</b> поддержки = следующий ориентир — следующие уровни поддержки (снижение).\n\n"

        "Обработка количества уровней:\n"
        "- Если доступен только <b>один уровень</b> (только поддержка ИЛИ только сопротивление):\n"
        "  • Опиши сценарий удержания и пробоя этого уровня.\n"
        "  • Если уровней дальше нет, прямо укажи, что следующих ориентиров по уровням нет.\n"
        "  • Не придумывай дополнительные уровни.\n"
        "- Если <b>уровни поддержки и сопротивления отсутствуют</b>:\n"
        "  • Прямо укажи, что уровни не были обнаружены по доступным данным.\n"
        "  • Не называй уровень алерта поддержкой или сопротивлением.\n"
        "  • Не указывай ценовые ориентиры, минимумы или максимумы.\n"
        "  • Опиши, что движение происходит вне сформированных зон и реакция может быть менее предсказуемой.\n\n"

        "Структура ответа:\n"
        "Абзац 1 (📍 текущая ситуация):\n"
        "- Укажи, что монета достигла ценового уровня алерта.\n"
        "- Укажи текущую цену.\n\n"

        "Абзац 2 (📊 поддержка):\n"
        "- Если есть уровень поддержки:\n"
        "  • Опиши сценарий удержания поддержки.\n"
        "  • Опиши сценарий пробоя поддержки.\n"
        "- Если поддержки нет — укажи, что уровни поддержки не обнаружены.\n\n"

        "Абзац 3 (📈 сопротивление / контекст):\n"
        "- Если есть уровень сопротивления:\n"
        "  • Опиши сценарий удержания сопротивления.\n"
        "  • Опиши сценарий пробоя сопротивления.\n"
        "- Если сопротивления нет — укажи, что уровни сопротивления не обнаружены.\n"
        "- Кратко опиши текущий <b>тренд</b>, опираясь только на направление движения цены.\n\n"

        "Важно: уровни поддержки и сопротивления указывай конкретными числами из текста.\n\n"

        "Техническое сообщение:\n"
        f"{fallback_text}\n"
    )